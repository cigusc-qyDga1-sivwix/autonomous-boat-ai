const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const fixture=JSON.parse(fs.readFileSync('app/data/live/latest.json','utf8'));
const r=fixture.forecast_races.find(x=>Array.isArray(x.racers)&&x.racers.length===6);
assert.ok(r,'Need actual saved six-racer data');
const window={};
const sandbox=vm.createContext({window,Number,Intl});
vm.runInContext(fs.readFileSync('app/race-visual.js','utf8'),sandbox);
const visual=window.BoatRaceVisual;
const original=JSON.stringify(r);
const table=visual.entryHTML(r);
assert.match(table,/出走表/);
assert.match(table,/全国勝率/);
assert.match(table,/モーター/);
assert.match(table,/2連対率/);
for(let i=1;i<=6;i++)assert.match(table,new RegExp('boat-entry-'+i));
assert.equal((table.match(/<tr><th><span class="boat-entry-lane/g)||[]).length,6);
const leading=r.racers.find(x=>Number(x.lane)===1);
assert.ok(table.includes(leading.name));
assert.ok(table.includes(Number(leading.national_win_rate).toFixed(2)));
assert.ok(table.includes(Number(leading.motor_top_2_percent).toFixed(1)+'%'));
const choices=visual.options(r);
assert.ok(choices.length>0&&choices.length<=3);
const simulated=visual.animationHTML(r);
assert.match(simulated,/展開予想アニメ/);
assert.match(simulated,/スタート → 第1ターンマーク → バックストレッチ/);
assert.match(simulated,/BACK STRETCH/);
assert.match(simulated,/実際の進入/);
assert.equal((simulated.match(/data-sim-boat="/g)||[]).length,6);
assert.equal((simulated.match(/data-sim-path="/g)||[]).length,6);
assert.equal((simulated.match(/data-sim-control="/g)||[]).length,3);
assert.ok(simulated.includes(choices[0]));
const ranking=visual.ranks('3-1-5');
assert.equal(ranking[3],1);
assert.equal(ranking[1],2);
assert.equal(ranking[5],3);
assert.deepEqual([ranking[2],ranking[4],ranking[6]],[4,5,6]);
assert.notEqual(visual.path(1,1),visual.path(1,6));
assert.equal(visual.tacticFor('1-3-2').id,'escape');
assert.equal(visual.tacticFor('2-1-3').id,'sashi');
assert.equal(visual.tacticFor('3-1-5').id,'makuri-zashi');
assert.equal(visual.tacticFor('4-5-1').id,'makuri');
assert.notEqual(visual.path(3,1,'makuri',3),visual.path(3,1,'makuri-zashi',3));
assert.notEqual(visual.path(1,1,'escape',1),visual.path(1,1,'sashi',1));
assert.match(visual.explanation('3-1-5'),/まくり差し/);
assert.match(visual.stageTexts('3-1-5')[1],/1M|まくり差し/);
assert.match(simulated,/data-sim-jump="turn"/);
assert.match(simulated,/data-sim-jump="back"/);
assert.match(simulated,/data-sim-speed="0.5"/);
assert.match(simulated,/data-sim-speed="1.5"/);
assert.match(simulated,/4〜6番手/);

assert.equal(JSON.stringify(r),original,'visualization must not modify any frozen bets');
const missing=visual.entryHTML({racers:[]});
assert.match(missing,/未取得/);
const injection={racers:Array.from({length:6},(_,i)=>({lane:i+1,name:'<script>alert(1)</script>',national_win_rate:5,motor_top_2_percent:30}))};
assert.ok(visual.entryHTML(injection).includes('&lt;script&gt;'));
assert.ok(!visual.entryHTML(injection).includes('<script>'));
console.log('BOAT LAB boat roster and conceptual animation HTML tests: PASS');
