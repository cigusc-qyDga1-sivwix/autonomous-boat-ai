const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const races=JSON.parse(fs.readFileSync('app/data/live/latest.json','utf8')).forecast_races;
const race=races.find(r=>r.racers?.length===6&&r.bets?.length);
assert.ok(race);
let clicks,changes,sliderInput;
const stored=new Map();
const fields={};
for(const key of ['[data-plan-edit]','[data-plan-formation]','[data-plan-result]','[data-plan-story]','[data-plan-stage]','[data-plan-status]'])fields[key]={innerHTML:'',textContent:''};
const paths={},boats={};
for(let i=1;i<=6;i++){
 paths['[data-plan-path="'+i+'"]']={d:'',setAttribute(k,v){if(k==='d')this.d=v;},getTotalLength(){return 1000;},getPointAtLength(t){return{x:100+t/2,y:270-t/6}}};
 boats['[data-plan-boat="'+i+'"]']={setAttribute(k,v){this[k]=v}};
}
const svg={querySelector:k=>paths[k]||boats[k]||null};
const slider={value:'0',addEventListener:(ev,fn)=>{if(ev==='input')sliderInput=fn}};
const card={querySelector:k=>k==='svg'?svg:k==='[data-plan-slider]'?slider:fields[k]||null,
 addEventListener:(ev,fn)=>{if(ev==='click')clicks=fn;if(ev==='change')changes=fn}};
const root={querySelector:k=>k==='[data-boat-tactics]'?card:null};
const localStorage={getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,v),removeItem:k=>stored.delete(k)};
const window={};const context=vm.createContext({window,localStorage,requestAnimationFrame:()=>1,cancelAnimationFrame:()=>{}});
vm.runInContext(fs.readFileSync('app/race-visual.js','utf8'),context);
vm.runInContext(fs.readFileSync('app/tactical-preview.js','utf8'),context);
const api=window.BoatRaceVisual;
const pristine=JSON.stringify(race);
api.mount(root,race);
assert.match(fields['[data-plan-edit]'].innerHTML,/data-plan-course/);
const chosen=1,target=4;
changes({target:{dataset:{planCourse:String(chosen)},value:String(target)}});
assert.equal(stored.size,1);
const modified=JSON.parse([...stored.values()][0]);
assert.equal(modified.boats[chosen-1].course,target);
assert.equal(modified.boats[target-1].course,chosen);
assert.equal(new Set(modified.boats.map(b=>b.course)).size,6);
changes({target:{dataset:{planGroup:'1'},value:'dash'}});
changes({target:{dataset:{planSt:'1'},value:'.11'}});
const modified2=JSON.parse([...stored.values()][0]);
assert.equal(modified2.boats[0].st,.11);
assert.equal(modified2.boats[0].group,'dash');
changes({target:{dataset:{planEnv:'wind'},value:'8'}});
assert.equal(JSON.parse([...stored.values()][0]).wind,8);
slider.value='700';sliderInput();
assert.match(fields['[data-plan-stage]'].textContent,/1M/);
assert.equal(JSON.stringify(race),pristine);
clicks({target:{closest:()=>({dataset:{planAction:'reset'}})}});
assert.equal(stored.size,0);
assert.equal(JSON.stringify(race),pristine);
api.dispose();
console.log('Tactical simulation UI editing, permutation and snapshot isolation: PASS');