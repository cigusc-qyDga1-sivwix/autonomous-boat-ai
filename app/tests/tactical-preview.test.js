const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const races=JSON.parse(fs.readFileSync('app/data/live/latest.json','utf8')).forecast_races;
const r=races.find(x=>x.racers&&x.racers.length===6&&x.bets&&x.bets.length>0);
assert.ok(r);
const original=JSON.stringify(r);
const window={};
const ctx=vm.createContext({window,Number,Intl});
vm.runInContext(fs.readFileSync('app/race-visual.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('app/tactical-preview.js','utf8'),ctx);
const api=window.BoatRaceVisual,mod=api.tactics;
const base=mod.defaults(r);
assert.equal(base.boats.length,6);
assert.equal(new Set(base.boats.map(b=>b.course)).size,6);
const plan=mod.analyze(r,base);
assert.equal(plan.order.length,6);
assert.equal(new Set(plan.order).size,6);
assert.equal(Object.keys(plan.rank).length,6);
assert.match(api.animationHTML(r),/data-plan-course="1"/);
assert.match(api.animationHTML(r),/data-plan-group="1"/);
assert.match(api.animationHTML(r),/data-plan-kind="1"/);
assert.match(api.animationHTML(r),/data-plan-st="1"/);
assert.match(api.animationHTML(r),/data-plan-env="wind"/);
assert.match(api.animationHTML(r),/data-plan-env="wave"/);
assert.match(api.animationHTML(r),/スロー/);
assert.match(api.animationHTML(r),/ダッシュ/);
assert.equal((api.animationHTML(r).match(/data-plan-path="/g)||[]).length,6);
assert.equal((api.animationHTML(r).match(/data-plan-boat="/g)||[]).length,6);
const swapped=JSON.parse(JSON.stringify(base));
[swapped.boats[0].course,swapped.boats[1].course]=[2,1];
assert.ok(mod.normalise(swapped));
const duplicate=JSON.parse(JSON.stringify(base));
duplicate.boats[0].course=duplicate.boats[1].course;
assert.equal(mod.normalise(duplicate),null,'Reject invalid entry permutations');
const st=JSON.parse(JSON.stringify(base));
st.boats[2].st=.08;st.boats[2].kind='makuri';
const changed=mod.analyze(r,st);
assert.notEqual(changed.boats[2].score,plan.boats[2].score);
st.wind=8;st.wave=12;st.relativeWind='cross';
const weather=mod.analyze(r,st);
assert.ok(weather.uncertainty>0);
assert.notEqual(mod.trajectory(changed.boats[2],changed.rank[3],changed),
 mod.trajectory(weather.boats[2],weather.rank[3],weather));
assert.equal(mod.normalise({...st,boats:st.boats.map(b=>({...b,st:-.2}))}).boats[0].st,null);
assert.equal(JSON.stringify(r),original,'Never mutate pre-cutoff frozen race');
console.log('Tactical entry/ST/weather/turn previews: PASS');
