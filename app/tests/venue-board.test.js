const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('app/venue-board.js','utf8');
const ctx={window:{},Intl,Date};
vm.runInNewContext(source,ctx);
const ui=ctx.window.BoatVenueBoard;
assert.equal(ui.VENUES.length,24,'Must show all 24 venues');
const live=JSON.parse(fs.readFileSync('app/data/live/latest.json','utf8'));
const forecast=live.forecast_races[0];
const props={now:'08:00',today:live.event_date,favorites:['徳山'],filter:'all',sort:'official'};
const html=ui.renderHome(live,props);
assert.match(html,/今日の開催一覧/);
assert.match(html,/data-open-venue=/);
assert.match(html,/data-favorite-venue="徳山"/);
assert.match(html,/data-venue-sort/);
assert.equal((html.match(/class="venue-card venue-theme-/g)||[]).length,24,'24 cards');
assert.equal(ui.entries(live,'08:00').length,24);
assert.ok(ui.sorted(ui.entries(live,'08:00'),{filter:'active'}).length<=24);
assert.equal((ui.renderHome(live,{...props,filter:'favorite'}).match(/class="venue-card venue-theme-/g)||[]).length,1);
const detail=ui.renderVenue(live,forecast.venue,props);
assert.match(detail,/全12R/);
assert.equal((detail.match(/class="venue-race(?: venue-race-[a-z]+)?"/g)||[]).length,12,'12 race slots');
assert.ok(detail.includes('data-race="'+forecast.venue+'|'+forecast.race+'"'),'Must link to the real prediction');
const noData={event_date:live.event_date,forecast_races:[],unforecast_races:[]};
const allGrey=ui.renderHome(noData,props);
assert.equal((allGrey.match(/venue-inactive/g)||[]).length,24);
assert.doesNotMatch(allGrey, /休催</);
assert.match(allGrey,/情報未取得/);
const sorted=ui.sorted(ui.entries(live,'08:00'),{filter:'favorite',favorites:['徳山']});
assert.equal(sorted[0].name,'徳山');
console.log('BOAT LAB venue-board tests: PASS');
